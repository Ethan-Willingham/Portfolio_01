'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const layouts=JSON.parse(fs.readFileSync(path.join(root,'assets/one-shift/places-v2/hotspots.json'),'utf8'));
for(const [room,layout] of Object.entries(layouts)){
  if(!(layout.width>0&&layout.height>0&&layout.targets.length))throw new Error('Invalid room '+room);
  const ids=new Set();
  for(const target of layout.targets){
    if(ids.has(target.id)||!target.path||target.bounds.length!==4||target.point.length!==2)throw new Error('Invalid target '+room+'/'+target.id);
    ids.add(target.id);
  }
}
fs.writeFileSync(path.join(root,'js/one-shift-place-layouts.js'),'// Generated by tools/build-one-shift-place-layouts.cjs from the measured image contours.\n(function(root){\n  \'use strict\';\n  root.OneShift.placeLayouts='+JSON.stringify(layouts,null,2)+';\n})(window);\n');
console.log('Built '+Object.keys(layouts).length+' room layouts.');
