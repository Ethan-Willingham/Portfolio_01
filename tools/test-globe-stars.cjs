#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const stars = require('../js/globe-stars.js');
const builder = require('./build-globe-stars.cjs');
const root = path.resolve(__dirname, '..');
const binary = fs.readFileSync(path.join(root, 'assets/data/stars-hyg-v41.bin'));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'assets/data/stars-hyg-v41.source.json')));
const catalog = stars.decode(binary);
const degree = Math.PI / 180;
let checks = 0;
function close(actual, expected, tolerance, label) {
  assert.ok(Math.abs(actual - expected) <= tolerance, `${label}: ${actual}, expected ${expected}`); checks++;
}
function star(id) {
  const index = catalog.ids.indexOf(id);
  assert.ok(index >= 0, `Missing HYG ${id}`); checks++;
  return { index, ra: catalog.ra[index], dec: catalog.dec[index], magnitude: catalog.magnitudes[index],
    colorIndex: catalog.colorIndices[index], color: catalog.colors.slice(index * 3, index * 3 + 3) };
}
function one(ra, dec, pmRa = 0, pmDec = 0) {
  return { count: 1, epoch: 2451545, ra: [ra], dec: [dec], pmRa: [pmRa], pmDec: [pmDec] };
}
function dot(a, b) { return a.reduce((sum, value, i) => sum + value * b[i], 0); }
function angle(a, b) { return Math.acos(Math.max(-1, Math.min(1, dot(a, b) / (Math.hypot(...a) * Math.hypot(...b))))); }
function wrap(angle) { return (angle + Math.PI * 3) % (Math.PI * 2) - Math.PI; }

async function main() {
  assert.equal(catalog.count, 5070); assert.equal(binary.length, 121712);
  assert.ok(binary.length < 150000); assert.equal(manifest.count, catalog.count);
  assert.equal(manifest.source.sha256, builder.SOURCE_SHA256);
  assert.equal(builder.sha256(binary), manifest.sha256);
  assert.equal(manifest.license, 'CC-BY-SA-4.0');
  assert.equal(catalog.missingColor.reduce((sum, flag) => sum + flag, 0), 23);
  assert.ok(!catalog.ids.includes(0)); assert.equal(new Set(catalog.ids).size, catalog.count);
  checks += 10;

  // Literal input values from pinned HYG 4.1, independent of the manifest writer.
  const sirius = star(32263), vega = star(90979), betelgeuse = star(27919), polaris = star(11734);
  close(sirius.ra, 1.7677953696021995, 1.2e-7, 'Sirius J2000 RA');
  close(sirius.dec, -0.291751258517685, 3e-8, 'Sirius J2000 declination');
  close(sirius.magnitude, -1.44, 1e-6, 'Sirius visual magnitude');
  close(vega.ra, 4.873563095509031, 2.4e-7, 'Vega J2000 RA');
  close(vega.dec, 0.6769031163973025, 6e-8, 'Vega J2000 declination');
  close(vega.magnitude, 0.03, 1e-6, 'Vega visual magnitude');
  close(betelgeuse.colorIndex, 1.5, 1e-6, 'Betelgeuse measured B-V');
  close(polaris.dec / degree, 89.264109, 0.00001, 'Polaris northern position');
  assert.ok(vega.color[2] > vega.color[0]); assert.ok(betelgeuse.color[0] > betelgeuse.color[2]); checks += 2;
  for (let i = 0; i < catalog.count; i++) {
    assert.ok(catalog.magnitudes[i] <= 6);
    if (i) assert.ok(catalog.magnitudes[i] >= catalog.magnitudes[i - 1]);
    const c = catalog.colors.slice(i * 3, i * 3 + 3);
    close(dot(c, [0.2126, 0.7152, 0.0722]), 1, 1e-7, `Visual luminance HYG ${catalog.ids[i]}`);
    if (catalog.missingColor[i]) {
      assert.ok(Number.isNaN(catalog.colorIndices[i])); assert.deepEqual(Array.from(c), [1, 1, 1]);
    }
  }
  close(stars.flux(0) / stars.flux(5), 100, 1e-12, 'Five-magnitude flux ratio');

  // Published ERFA (SOFA-derived) reference values, not generated by this module.
  // https://github.com/liberfa/erfa/blob/master/src/t_erfa_c.c
  // t_gmst06: UT1 = TT = JD 2400000.5 + 53736.0.
  close(stars.gmstRadians(new Date('2006-01-01T00:00:00Z')),
    1.754174971870091203, 1e-12, 'ERFA GMST06');
  // t_pmat76: TT = JD 2400000.5 + 50123.9999. Numeric matrix facts are
  // reproduced with ERFA attribution and license in stars-erfa-LICENSE.txt.
  const precessionDate = (2400000.5 + 50123.9999 - 2440587.5) * 86400000;
  const reference = [0.9999995504328350733, 0.8696632209480960785e-3, 0.3779153474959888345e-3,
    -0.8696632209485112192e-3, 0.9999996218428560614, -0.1643284776111886407e-6,
    -0.3779153474950335077e-3, -0.1643306746147366896e-6, 0.9999999285899790119];
  const matrix = stars.precessionMatrix(precessionDate);
  reference.forEach((value, i) => close(matrix[i], value, 1e-14, `ERFA precession matrix ${i}`));

  // USNO's sidereal-time definition: RA = GMST is on Greenwich's meridian.
  // At J2000, precession is exactly identity. Increasing RA goes east (-Z).
  const j2000 = new Date('2000-01-01T12:00:00Z'), q = stars.gmstRadians(j2000);
  const greenwich = stars.worldPositions(one(q, 0), j2000);
  close(greenwich[0], 1, 1e-7, 'Greenwich +X'); close(greenwich[1], 0, 1e-7, 'Equator Y');
  close(greenwich[2], 0, 1e-7, 'Greenwich Z');
  const east = stars.worldPositions(one((q + Math.PI / 2) % (2 * Math.PI), 0), j2000);
  close(east[0], 0, 1e-7, 'East X'); close(east[2], -1, 1e-7, 'East -Z');
  const north = stars.worldPositions(one(0, Math.PI / 2), j2000);
  close(north[1], 1, 1e-7, 'North +Y');

  // One solar day brings the stellar sphere about 0.986 degrees farther west.
  const inertial = one(sirius.ra, sirius.dec);
  const a = stars.worldPositions(inertial, j2000), b = stars.worldPositions(inertial, +j2000 + 86400000);
  const longitudeShift = wrap(Math.atan2(-b[2], b[0]) - Math.atan2(-a[2], a[0])) / degree;
  close(longitudeShift, -0.9856, 0.0002, 'Daily stellar rotation direction and rate');
  const sidereal = stars.worldPositions(inertial, +j2000 + 86164090.5);
  // The moving mean equinox and pole add about 0.14 arcsecond of precession/day.
  close(angle(a, sidereal), 0, 8e-7, 'Same sky after a sidereal day, within daily precession');

  // Proper motion applies in tangent coordinates, including near the pole.
  const highMotion = one(0, 89.9 * degree, 1000, 0);
  const after = new Date('2100-01-01T12:00:00Z'), fixed = one(0, 89.9 * degree);
  const moved = stars.worldPositions(highMotion, after), unmoved = stars.worldPositions(fixed, after);
  const years = (stars.julianDate(after) - 2451545) / 365.25;
  close(angle(moved, unmoved), Math.atan(years * Math.PI / (180 * 3600)), 1e-7,
    'mu_alpha*cos(delta) avoids polar amplification');

  // Rotation preserves unit length and pairwise star separations across the picker range.
  const first = star(32263), second = star(90979);
  const j2000Pair = { count: 2, epoch: 2451545, ra: [first.ra, second.ra], dec: [first.dec, second.dec], pmRa: [0, 0], pmDec: [0, 0] };
  const initial = stars.worldPositions(j2000Pair, j2000), separation = angle(initial.slice(0, 3), initial.slice(3, 6));
  for (const date of ['1900-01-01T00:00:00Z', '2026-10-05T12:00:00Z', '2100-12-31T23:59:00Z']) {
    const positions = stars.worldPositions(catalog, new Date(date), 65);
    for (let i = 0; i < catalog.count; i++) close(Math.hypot(...positions.slice(i * 3, i * 3 + 3)), 65, 5e-6, `Sphere radius ${date} ${i}`);
    const pair = stars.worldPositions(j2000Pair, new Date(date));
    close(angle(pair.slice(0, 3), pair.slice(3, 6)), separation, 8e-8, `Constellation geometry ${date}`);
  }
  const target = new Float32Array(catalog.count * 3);
  assert.equal(stars.worldPositions(catalog, j2000, 65, target), target); checks++;
  assert.throws(() => stars.worldPositions(catalog, new Date('invalid')), /Invalid star date/);
  assert.throws(() => stars.worldPositions(catalog, j2000, 0), /Invalid star radius/);
  assert.throws(() => stars.worldPositions(catalog, j2000, 1, new Float32Array(2)), /Star target/); checks += 3;

  // Corrupt or partial external data fails closed.
  assert.throws(() => stars.decode(binary.subarray(0, 31)), /Truncated/);
  assert.throws(() => stars.decode(binary.subarray(0, binary.length - 1)), /Invalid.*header/);
  const corruptHeader = Buffer.from(binary); corruptHeader[0] = 0;
  assert.throws(() => stars.decode(corruptHeader), /Invalid.*header/);
  const corruptFlags = Buffer.from(binary); corruptFlags[32 + 23] = 2;
  assert.throws(() => stars.decode(corruptFlags), /Invalid.*record/);
  const duplicateId = Buffer.from(binary); duplicateId.writeUInt32LE(duplicateId.readUInt32LE(32), 56);
  assert.throws(() => stars.decode(duplicateId), /Invalid.*record/); checks += 5;

  // Builder proves inclusion rules on a small independent CSV, including quoted names.
  const tinyCsv = 'id,hip,proper,rarad,decrad,pmra,pmdec,mag,ci\n' +
    '0,,Sun,0,0,0,0,-26.7,0.65\n1,1,"A, quoted star",1,0.2,10,-20,2,0.1\n' +
    '2,2,Faint,2,0,0,0,6.01,0.6\n3,3,Unknown color,3,-0.5,0,0,6,\n';
  const tiny = builder.buildCatalog(tinyCsv), decoded = stars.decode(tiny.binary);
  assert.equal(decoded.count, 2); assert.deepEqual(Array.from(decoded.ids), [1, 3]);
  assert.equal(tiny.stars[0].name, 'A, quoted star'); assert.equal(decoded.missingColor[1], 1);
  assert.ok(builder.buildCatalog(tinyCsv).binary.equals(tiny.binary));
  assert.throws(() => builder.buildCatalog(tinyCsv + '1,1,Duplicate,1,0.2,0,0,1,0\n'), /duplicate/); checks += 6;

  const originalFetch = global.fetch, signal = new AbortController().signal;
  try {
    let observed;
    global.fetch = async (url, options) => { observed = { url, options }; return { ok: true, arrayBuffer: async () => binary.buffer.slice(binary.byteOffset, binary.byteOffset + binary.byteLength) }; };
    const loaded = await stars.load('/actual-stars.bin', { signal });
    assert.equal(loaded.count, 5070); assert.equal(observed.url, '/actual-stars.bin'); assert.equal(observed.options.signal, signal);
    global.fetch = async () => ({ ok: false, status: 404 });
    await assert.rejects(stars.load('/missing.bin'), /HTTP 404/); checks += 4;
  } finally { global.fetch = originalFetch; }
  console.log(`Star catalog checks passed (${checks} checks, ${catalog.count} genuine stars)`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
